"""Fixtures and summary writer for the real-data validation suite (T-1.6).

These tests read the real processed pilot data and are marked ``data``; ``make test``
deselects them (``-m "not data"`` in pyproject.toml). Run them with ``make validate``.

Environment overrides (used by the sabotage checks, never needed in normal runs):
  MILANO_ISO_PROCESSED_GPKG  path of the GeoPackage to validate instead of processed/pilot.gpkg
  MILANO_ISO_VALIDATE_OUT    directory for validate_summary.md and landmarks_check.csv
"""

import os
from pathlib import Path

import pyogrio
import pytest
from milano_iso import config

OUT_DIR = Path(
    os.environ.get("MILANO_ISO_VALIDATE_OUT", config.REPO_ROOT / "reports" / "artifacts" / "T-1.6")
)
GPKG = Path(os.environ.get("MILANO_ISO_PROCESSED_GPKG", config.PROCESSED_DIR / "pilot.gpkg"))
OSM_INTERIM = config.INTERIM_DIR / "osm_pilot.gpkg"
DROP_LOG = config.PROCESSED_DIR / "drop_log.csv"
DBT_ZIP = config.RAW_DIR / "dbt2020" / "DBT_2020.zip"

_REPORT_SECTIONS: dict[str, str] = {}
_OUTCOMES: list[tuple[str, str, str]] = []  # (nodeid, outcome, reason)


class Report:
    def add(self, title: str, text: str) -> None:
        _REPORT_SECTIONS[title] = text


def pytest_collection_modifyitems(items):
    for item in items:
        if "tests/data/" in item.nodeid.replace("\\", "/"):
            item.add_marker(pytest.mark.data)


def pytest_generate_tests(metafunc):
    if "layer_name" in metafunc.fixturenames:
        names = sorted(n for n, _ in pyogrio.list_layers(GPKG)) if GPKG.exists() else []
        metafunc.parametrize("layer_name", names)


@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_makereport(item, call):
    outcome = yield
    rep = outcome.get_result()
    if rep.when == "call" or (rep.when == "setup" and rep.outcome != "passed"):
        reason = ""
        if rep.skipped and isinstance(rep.longrepr, tuple):
            reason = str(rep.longrepr[2]).removeprefix("Skipped: ")
        elif rep.failed:
            reason = (rep.longreprtext.strip().splitlines() or [""])[-1][:300]
        _OUTCOMES.append((item.nodeid, rep.outcome, reason))


def pytest_sessionfinish(session, exitstatus):
    if not _OUTCOMES:
        return
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    n = {k: sum(1 for _, o, _ in _OUTCOMES if o == k) for k in ("passed", "failed", "skipped")}
    lines = [
        "# Data validation summary (T-1.6)",
        "",
        "Generated by `make validate` (pytest -m data). No timestamps or absolute paths.",
        f"Validated file: `{GPKG.name}`",
        "",
        (
            f"**passed {n['passed']}, failed {n['failed']}, skipped {n['skipped']}** "
            f"(total {len(_OUTCOMES)})"
        ),
        "",
        "## Results",
        "",
        "| Test | Outcome | Reason / last message |",
        "|---|---|---|",
    ]
    for nodeid, outcome, reason in _OUTCOMES:
        lines.append(f"| `{nodeid}` | {outcome} | {reason.replace('|', '/')} |")
    for title in sorted(_REPORT_SECTIONS):
        lines += ["", f"## {title}", "", _REPORT_SECTIONS[title].rstrip()]
    (OUT_DIR / "validate_summary.md").write_text(
        "\n".join(lines) + "\n", encoding="utf-8", newline="\n"
    )


@pytest.fixture(scope="session")
def report() -> Report:
    return Report()


@pytest.fixture(scope="session")
def gpkg() -> Path:
    assert GPKG.exists(), f"processed GeoPackage not found: {GPKG}; run `make data` first"
    return GPKG


@pytest.fixture(scope="session")
def layers(gpkg) -> dict:
    return {
        name: pyogrio.read_dataframe(gpkg, layer=name)
        for name in sorted(n for n, _ in pyogrio.list_layers(gpkg))
    }
