"""Write reports/artifacts/T-6.1/city_summary.md from the built city data (T-6.1).

Reads $MILANO_ISO_DATA: processed/city.gpkg, processed/drop_log_city.csv, tiles/city/. Every
number is computed here from those files; nothing is typed in. Run after
``make data tiles EXTENT=city``: ``uv run python pipeline/scripts/city_summary.py``.
"""

import csv
import gzip
import json
import statistics
from collections import Counter
from pathlib import Path

import pyogrio
from milano_iso import config, extent

OUT = config.REPO_ROOT / "reports" / "artifacts" / "T-6.1" / "city_summary.md"
BUDGET_ADR_0022 = 256_000  # ADR-0022, docs/VERIFICATION.md section 5
BUDGET_CARD = 250_000  # "250 KB" of the task card, taken as 250,000 bytes


def gz(data: bytes) -> int:
    return len(gzip.compress(data, compresslevel=9, mtime=0))


def pct(sorted_values, q):
    """Nearest-rank percentile of a sorted list."""
    k = max(0, min(len(sorted_values) - 1, -(-len(sorted_values) * q // 100) - 1))
    return sorted_values[int(k)]


def main() -> None:
    gpkg = extent.processed_gpkg("city")
    tiles = extent.tiles_dir("city")
    lines = [
        "# T-6.1 city summary",
        "",
        "Generated by `pipeline/scripts/city_summary.py` from the real city build; ",
    ]
    lines[-1] += "no number is typed in."
    lines += [
        "",
        "## Features per layer (`processed/city.gpkg`)",
        "",
        "| layer | features |",
        "|---|---:|",
    ]
    total = 0
    for name in sorted(n for n, _ in pyogrio.list_layers(gpkg)):
        n = pyogrio.read_info(gpkg, layer=name)["features"]
        total += n
        lines.append(f"| {name} | {n} |")
    lines.append(f"| **total** | {total} |")

    files = sorted(p for p in tiles.iterdir() if p.is_file())
    raw = {p.name: p.read_bytes() for p in files}
    glbs = {n: b for n, b in raw.items() if n.endswith(".glb")}
    gz_glb = {n: gz(b) for n, b in glbs.items()}
    raw_total = sum(len(b) for b in raw.values())
    gz_total = sum(gz(b) for b in raw.values())
    by_ext = Counter(Path(n).suffix for n in raw)
    sizes = sorted(gz_glb.values())
    lines += [
        "",
        "## Tiles (`tiles/city/`)",
        "",
        f"- files: {len(raw)} ({', '.join(f'{k} {v}' for k, v in sorted(by_ext.items()))})",
        f"- tiles (one .glb each): {len(glbs)}",
        f"- all files, raw: {raw_total} bytes; gzip-9: {gz_total} bytes",
        f"- .glb files only, raw: {sum(len(b) for b in glbs.values())} bytes; gzip-9: {sum(sizes)} bytes",
        "",
        "Tile size = gzip-9 of the .glb (what the budget of ADR-0022 measures):",
        "",
        f"- min {sizes[0]}, median {statistics.median(sizes):.0f}, p95 {pct(sizes, 95)}, max {sizes[-1]} bytes",
    ]
    for label, budget in (
        ("ADR-0022 budget 256000", BUDGET_ADR_0022),
        ("card budget 250000", BUDGET_CARD),
    ):
        over = sorted(n.removesuffix(".glb") for n, s in gz_glb.items() if s > budget)
        lines.append(
            f"- tiles above the {label} bytes gzip: {len(over)}"
            + (f" ({', '.join(over)})" if over else "")
        )
    idx = raw["index.json"]
    lines += [
        "",
        "## Other files",
        "",
        f"- `index.json`: {len(idx)} bytes raw, {gz(idx)} bytes gzip-9",
        f"- `tiles.json`: {len(raw['tiles.json'])} bytes raw, {gz(raw['tiles.json'])} bytes gzip-9",
        f"- `minimap.svg`: {len(raw['minimap.svg'])} bytes raw, {gz(raw['minimap.svg'])} bytes gzip-9",
    ]

    with extent.drop_log("city").open(encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f))
    lines += [
        "",
        "## Drop-log totals by reason (`processed/drop_log_city.csv`)",
        "",
        f"{len(rows)} rows.",
        "",
        "| layer | action | reason | rows |",
        "|---|---|---|---:|",
    ]
    for (layer, action, reason), n in sorted(
        Counter((r["layer"], r["action"], r["reason"]) for r in rows).items()
    ):
        lines.append(f"| {layer} | {action} | {reason} | {n} |")

    export = json.loads(
        (
            config.REPO_ROOT
            / "reports"
            / "artifacts"
            / "T-6.1"
            / "city"
            / "T-2.3"
            / "export_summary.json"
        ).read_text(encoding="utf-8")
    )
    lines += ["", "## Export checks (`city/T-2.3/export_summary.json`)", ""]
    for k, v in export["checks"].items():
        if k != "tiles_outside_pilot_aoi":
            lines.append(f"- {k}: {v}")
    lines.append(
        f"- tiles outside the extent's own tiles: {len(export['checks']['tiles_outside_pilot_aoi'])}"
    )
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
